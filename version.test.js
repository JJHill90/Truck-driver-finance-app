const { formatVersionLabel, HAULAGE_PR_NUMBER } = require("./lib/version");

describe("formatVersionLabel", () => {
  it("uses .1–.50 then rounds to 1.00 and climbs 1.01…1.50 → 2.00", () => {
    expect(formatVersionLabel(1)).toBe("Version .1");
    expect(formatVersionLabel(49)).toBe("Version .49");
    expect(formatVersionLabel(50)).toBe("Version .50");
    expect(formatVersionLabel(51)).toBe("Version 1.00");
    expect(formatVersionLabel(52)).toBe("Version 1.01");
    expect(formatVersionLabel(53)).toBe("Version 1.02");
    expect(formatVersionLabel(100)).toBe("Version 1.49");
    expect(formatVersionLabel(101)).toBe("Version 1.50");
    expect(formatVersionLabel(102)).toBe("Version 2.00");
    expect(formatVersionLabel(103)).toBe("Version 2.01");
    expect(formatVersionLabel(104)).toBe("Version 2.02");
    expect(formatVersionLabel(105)).toBe("Version 2.03");
    expect(formatVersionLabel(106)).toBe("Version 2.04");
    expect(formatVersionLabel(107)).toBe("Version 2.05");
    expect(formatVersionLabel(152)).toBe("Version 2.50");
    expect(formatVersionLabel(153)).toBe("Version 3.00");
    expect(formatVersionLabel(154)).toBe("Version 3.01");
    expect(formatVersionLabel(155)).toBe("Version 3.02");
    expect(formatVersionLabel(156)).toBe("Version 3.03");
    expect(formatVersionLabel(157)).toBe("Version 3.04");
    expect(formatVersionLabel(158)).toBe("Version 3.05");
    expect(formatVersionLabel(159)).toBe("Version 3.06");
    expect(formatVersionLabel(160)).toBe("Version 3.07");
    expect(formatVersionLabel(161)).toBe("Version 3.08");
    expect(formatVersionLabel(162)).toBe("Version 3.09");
    expect(formatVersionLabel(163)).toBe("Version 3.10");
    expect(formatVersionLabel(164)).toBe("Version 3.11");
    expect(formatVersionLabel(165)).toBe("Version 3.12");
    expect(formatVersionLabel(166)).toBe("Version 3.13");
    expect(formatVersionLabel(167)).toBe("Version 3.14");
    expect(formatVersionLabel(168)).toBe("Version 3.15");
    expect(formatVersionLabel(169)).toBe("Version 3.16");
    expect(formatVersionLabel(170)).toBe("Version 3.17");
    expect(formatVersionLabel(171)).toBe("Version 3.18");
    expect(formatVersionLabel(172)).toBe("Version 3.19");
    expect(formatVersionLabel(173)).toBe("Version 3.20");
    expect(formatVersionLabel(174)).toBe("Version 3.21");
    expect(formatVersionLabel(175)).toBe("Version 3.22");
    expect(formatVersionLabel(176)).toBe("Version 3.23");
    expect(formatVersionLabel(177)).toBe("Version 3.24");
    expect(formatVersionLabel(178)).toBe("Version 3.25");
    expect(formatVersionLabel(179)).toBe("Version 3.26");
    expect(formatVersionLabel(180)).toBe("Version 3.27");
    expect(formatVersionLabel(181)).toBe("Version 3.28");
    expect(formatVersionLabel(182)).toBe("Version 3.29");
    expect(formatVersionLabel(183)).toBe("Version 3.30");
    expect(formatVersionLabel(184)).toBe("Version 3.31");
    expect(formatVersionLabel(185)).toBe("Version 3.32");
    expect(formatVersionLabel(186)).toBe("Version 3.33");
    expect(formatVersionLabel(187)).toBe("Version 3.34");
    expect(formatVersionLabel(188)).toBe("Version 3.35");
    expect(formatVersionLabel(193)).toBe("Version 3.40");
    expect(formatVersionLabel(194)).toBe("Version 3.41");
    expect(formatVersionLabel(196)).toBe("Version 3.43");
    expect(formatVersionLabel(200)).toBe("Version 3.47");
  });

  it("maps the current PR constant (this PR is #200 → Version 3.47)", () => {
    expect(HAULAGE_PR_NUMBER).toBe(200);
    expect(formatVersionLabel(200)).toBe("Version 3.47");
  });
});
